def load_alltoall_results(results_dir):
    json_files = glob.glob(os.path.join(results_dir, 'K_scan_*.json'))
    if not json_files:
        return None
    json_file = sorted(json_files)[-1]
    with open(json_file) as f:
        data = json.load(f)
    print(f"  Loaded all-to-all data: {json_file}")
    return data


def parse_network_filename(filename):
    basename = os.path.basename(filename)
    params = {}
    for net in ['ER', 'BA', 'WS', 'RR']:
        if f'_{net}_' in basename:
            params['network'] = net
            break
    patterns = {
        'N': r'_N(\d+)',
        'kave': r'_kave([\d.]+)',
        'K': r'_K([\d.]+)',
        'eps': r'_eps(-?[\d.]+)',
        'interval': r'_interval([\d.]+)',
    }
    for key, pattern in patterns.items():
        match = re.search(pattern, basename)
        if match:
            params[key] = float(match.group(1))
    params['random'] = '_random' in basename
    return params


def extract_steady_state_R(filepath, t_fraction=0.5):
    try:
        df = pd.read_csv(filepath)
    except Exception as e:
        print(f"  Warning: Could not read {filepath}: {e}")
        return None, None
    if 'R_mean' not in df.columns:
        return None, None
    tmax = df['time'].max()
    mask = df['time'] > tmax * t_fraction
    R_mean = df.loc[mask, 'R_mean'].mean()
    R_columns = [col for col in df.columns if col.startswith('R_run')]
    if R_columns:
        R_ss_per_run = df.loc[mask, R_columns].mean(axis=0)
        R_std = R_ss_per_run.std()
    else:
        R_std = 0.0
    return R_mean, R_std


def load_network_results(results_dir):
    csv_files = glob.glob(os.path.join(results_dir, 'results_*_all_runs.csv'))
    records = []
    for filepath in sorted(csv_files):
        params = parse_network_filename(filepath)
        if 'network' not in params:
            continue
        R_mean, R_std = extract_steady_state_R(filepath)
        if R_mean is not None:
            params['R_mean'] = R_mean
            params['R_std'] = R_std
            records.append(params)
    if not records:
        return pd.DataFrame()
    return pd.DataFrame(records)


