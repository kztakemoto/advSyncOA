def S_func(R):
    if R < 1e-12: return 1.0 / np.pi
    if R > 1 - 1e-12: return 0.0
    return (1 - R**2) * np.arctanh(R) / (np.pi * R)

def R_kick(R, eps):
    return R * np.cos(eps) + 2 * np.sin(eps) * S_func(R)


def oa_steady_state_homo(K, Delta, eps, tau, n_iter=3000, tol=1e-8):
    R = 0.01
    for _ in range(n_iter):
        R_old = R
        n_steps = 50
        dt = tau / n_steps
        for __ in range(n_steps):
            dR = -Delta * R + (K / 2) * R * (1 - R**2)
            R = max(0.0, min(1.0, R + dt * dR))
        R = max(0.0, min(1.0, R_kick(R, eps)))
        if abs(R - R_old) < tol:
            break
    return R


def get_degree_dist_coarse(network_type, kave, N=None):
    if network_type == 'ER':
        k_max = int(kave + 5 * np.sqrt(kave))
        k_all = np.arange(1, k_max + 1)
        Pk_all = poisson.pmf(k_all, kave)
        Pk_all /= Pk_all.sum()
        n_bins = min(15, len(k_all))
        edges = np.linspace(0.5, k_max + 0.5, n_bins + 1)
        k_rep, Pk_rep = [], []
        for i in range(n_bins):
            mask = (k_all >= edges[i]) & (k_all < edges[i + 1])
            if mask.sum() > 0 and Pk_all[mask].sum() > 1e-10:
                k_rep.append(np.average(k_all[mask], weights=Pk_all[mask]))
                Pk_rep.append(Pk_all[mask].sum())
        k_rep, Pk_rep = np.array(k_rep), np.array(Pk_rep)
        return k_rep, Pk_rep / Pk_rep.sum()

    elif network_type == 'BA':
        m = int(kave / 2)
        if N is not None:
            import networkx as nx
            all_degrees = []
            n_samples = min(20, max(5, N // 200))
            for s in range(n_samples):
                g = nx.barabasi_albert_graph(N, m, seed=s * 137)
                all_degrees.extend([d for _, d in g.degree()])
            all_degrees = np.array(all_degrees)
            k_min = m
            k_max = int(np.percentile(all_degrees, 99.5))
            k_all_clean = []
            Pk_all_clean = []
            for k in range(k_min, k_max + 1):
                cnt = np.sum(all_degrees == k)
                if cnt > 0:
                    k_all_clean.append(float(k))
                    Pk_all_clean.append(float(cnt))
            k_all = np.array(k_all_clean)
            Pk_all = np.array(Pk_all_clean)
            Pk_all /= Pk_all.sum()
        else:
            k_max = 300
            k_all = np.arange(m, k_max + 1).astype(float)
            Pk_all = 2.0 * m * (m + 1) / (k_all * (k_all + 1) * (k_all + 2))
            Pk_all /= Pk_all.sum()

        edges = np.unique(np.logspace(
            np.log10(k_all[0] - 0.5), np.log10(k_all[-1] + 0.5), 21
        ).astype(int))
        k_rep, Pk_rep = [], []
        for i in range(len(edges) - 1):
            mask = (k_all >= edges[i]) & (k_all < edges[i + 1])
            if mask.sum() > 0 and Pk_all[mask].sum() > 1e-10:
                k_rep.append(np.average(k_all[mask], weights=Pk_all[mask]))
                Pk_rep.append(Pk_all[mask].sum())
        k_rep, Pk_rep = np.array(k_rep), np.array(Pk_rep)
        return k_rep, Pk_rep / Pk_rep.sum()

    elif network_type == 'RR':
        d = int(kave)
        return np.array([float(d)]), np.array([1.0])

    else:
        raise ValueError(f"OA theory not applicable to {network_type}")


def oa_steady_state_hetero(k_arr, Pk, K, Delta, eps, tau, n_iter=3000, tol=1e-8):
    n = len(k_arr)
    k_mean = np.sum(k_arr * Pk)
    R_k = np.full(n, 0.03)
    for _ in range(n_iter):
        R_old = R_k.copy()
        n_steps = 50
        dt = tau / n_steps
        for __ in range(n_steps):
            H = np.sum(k_arr * Pk * R_k) / k_mean
            dR = -Delta * R_k + (k_arr * K / 2) * H * (1 - R_k**2)
            R_k = np.clip(R_k + dt * dR, 0, 1)
        for i in range(n):
            R_k[i] = max(0.0, min(1.0, R_kick(R_k[i], eps)))
        if np.max(np.abs(R_k - R_old)) < tol:
            break
    return np.sum(Pk * R_k)


def compute_theory_curve(network_type, K_values, Delta, eps, tau, kave=6.0, N=None):
    R_theory = []
    if network_type == 'alltoall':
        for K in K_values:
            R_theory.append(oa_steady_state_homo(K, Delta, eps, tau))
    else:
        k_arr, Pk = get_degree_dist_coarse(network_type, kave, N=N)
        for K in K_values:
            R_theory.append(oa_steady_state_hetero(k_arr, Pk, K, Delta, eps, tau))
    return np.array(R_theory)


