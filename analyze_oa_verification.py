def plot_alltoall_transition(alltoall_data, Delta, tau, output_dir):
    if alltoall_data is None:
        print("  No all-to-all data found, skipping.")
        return

    K_c = 2 * Delta
    K_ratios = np.array(alltoall_data['K_ratio'])
    eps_values = alltoall_data.get('eps_values', [0.0, 0.05, -0.05])
    eps_pos = sorted(set(abs(e) for e in eps_values if e > 0))
    n_pos = len(eps_pos)
    red_colors  = [cm.Reds(0.4  + 0.5 * i / max(n_pos - 1, 1)) for i in range(n_pos)]
    blue_colors = [cm.Blues(0.4 + 0.5 * i / max(n_pos - 1, 1)) for i in range(n_pos)]

    fig, ax = plt.subplots(figsize=(5.5, 5))

    K_th = np.linspace(K_ratios.min() * K_c, K_ratios.max() * K_c, 80)
    K_th_ratio = K_th / K_c

    # Theory curves
    R_th_0 = compute_theory_curve('alltoall', K_th, Delta, 0.0, tau)
    ax.plot(K_th_ratio, R_th_0, 'k-', lw=2.5)
    for i, eps_v in enumerate(eps_pos):
        ax.plot(K_th_ratio,
                compute_theory_curve('alltoall', K_th, Delta,  eps_v, tau),
                '-', color=red_colors[i], lw=2.5)
        ax.plot(K_th_ratio,
                compute_theory_curve('alltoall', K_th, Delta, -eps_v, tau),
                '-', color=blue_colors[i], lw=2.5)

    # Simulation points
    key0 = 'R_eps+0.000'
    if key0 in alltoall_data:
        ax.plot(K_ratios, alltoall_data[key0], 'o', color='k', ms=7,
                markerfacecolor='none', markeredgewidth=1.5, alpha=0.8)
    elif 'R_none' in alltoall_data:
        ax.plot(K_ratios, alltoall_data['R_none'], 'o', color='k', ms=7,
                markerfacecolor='none', markeredgewidth=1.5, alpha=0.8)
    for i, eps_v in enumerate(eps_pos):
        key_p = f'R_eps+{eps_v:.3f}'
        key_n = f'R_eps-{eps_v:.3f}'
        if key_p in alltoall_data:
            ax.plot(K_ratios, alltoall_data[key_p], 'o', color=red_colors[i],
                    ms=7, markerfacecolor='none', markeredgewidth=1.5, alpha=0.8)
        if key_n in alltoall_data:
            ax.plot(K_ratios, alltoall_data[key_n], 'o', color=blue_colors[i],
                    ms=7, markerfacecolor='none', markeredgewidth=1.5, alpha=0.8)

    ax.axvline(1.0, color='gray', ls=':', lw=1.2, alpha=0.5)
    ax.set_xlabel(r'$K / K_c$')
    ax.set_ylabel('$R$')
    ax.set_ylim(-0.02, 1.02)
    make_legends(ax, eps_pos, red_colors, blue_colors)

    plt.tight_layout()
    fname = os.path.join(output_dir, 'transition_alltoall.png')
    plt.savefig(fname, dpi=150, bbox_inches='tight')
    plt.savefig(fname.replace('.png', '.pdf'), bbox_inches='tight')
    plt.savefig(fname.replace('.png', '.eps'), bbox_inches='tight')
    plt.close()
    print(f"  Saved {fname}")


def plot_network_transition_simple(df, network_type, Delta, tau, kave, output_dir, panel_label=None):
    subset = df[df['network'] == network_type].copy()
    if len(subset) == 0:
        print(f"  No data for {network_type}, skipping.")
        return

    if 'eps' not in subset.columns:
        subset['eps'] = 0.0
    subset['eps'] = subset['eps'].fillna(0.0)

    all_eps = sorted(subset['eps'].unique())
    eps_pos = sorted(set(abs(e) for e in all_eps if e > 0.001))
    n_pos = len(eps_pos)
    red_colors  = [cm.Reds(0.4  + 0.5 * i / max(n_pos - 1, 1)) for i in range(n_pos)]
    blue_colors = [cm.Blues(0.4 + 0.5 * i / max(n_pos - 1, 1)) for i in range(n_pos)]

    try:
        k_arr, Pk = get_degree_dist_coarse(network_type, kave)
        k_mean = np.sum(k_arr * Pk)
        k2 = np.sum(k_arr**2 * Pk)
        K_c = 2 * Delta * k_mean / k2
        has_theory = True
    except ValueError:
        K_c = None
        has_theory = False

    fig, ax = plt.subplots(figsize=(5.5, 5))

    if has_theory:
        K_min = max(subset['K'].min() * 0.5, 0.001)
        K_max = subset['K'].max() * 1.1
        K_th = np.linspace(K_min, K_max, 80)

        ax.plot(K_th,
                compute_theory_curve(network_type, K_th, Delta, 0.0, tau, kave),
                'k-', lw=2.5)
        for i, eps_v in enumerate(eps_pos):
            ax.plot(K_th,
                    compute_theory_curve(network_type, K_th, Delta,  eps_v, tau, kave),
                    '-', color=red_colors[i], lw=2.5)
            ax.plot(K_th,
                    compute_theory_curve(network_type, K_th, Delta, -eps_v, tau, kave),
                    '-', color=blue_colors[i], lw=2.5)
        ax.axvline(K_c, color='gray', ls=':', lw=1.2, alpha=0.5)

    # Simulation points
    def _pts(eps_val):
        s = subset[np.isclose(subset['eps'], eps_val, atol=0.001)]
        if 'random' in s.columns:
            s = s[~s['random']]
        return s.sort_values('K')

    s0 = _pts(0.0)
    if len(s0):
        ax.plot(s0['K'], s0['R_mean'], 'o', color='k', ms=7, alpha=0.8,
                markerfacecolor='none', markeredgewidth=1.5)
    for i, eps_v in enumerate(eps_pos):
        sp = _pts( eps_v); sn = _pts(-eps_v)
        if len(sp):
            ax.plot(sp['K'], sp['R_mean'], 'o', color=red_colors[i], ms=7,
                    alpha=0.8, markerfacecolor='none', markeredgewidth=1.5)
        if len(sn):
            ax.plot(sn['K'], sn['R_mean'], 'o', color=blue_colors[i], ms=7,
                    alpha=0.8, markerfacecolor='none', markeredgewidth=1.5)

    ax.set_xlabel('$K$')
    ax.set_ylabel('$R$')
    ax.set_ylim(-0.02, 1.02)
    make_legends(ax, eps_pos, red_colors, blue_colors)

    if panel_label is not None:
        ax.set_title(f'({panel_label}) {network_type}')

    plt.tight_layout()
    fname = os.path.join(output_dir, f'transition_{network_type}.png')
    plt.savefig(fname, dpi=150, bbox_inches='tight')
    plt.savefig(fname.replace('.png', '.pdf'), bbox_inches='tight')
    plt.savefig(fname.replace('.png', '.eps'), bbox_inches='tight')
    plt.close()
    print(f"  Saved {fname}")


